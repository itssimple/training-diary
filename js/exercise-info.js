/** Library fields filled from STARTER_INFO (lines joined with "\n"). */
export function starterInfoFields(id) {
  const info = STARTER_INFO[id];
  if (!info) return null;
  return {
    primaryMuscles: [...info.primary],
    instructions: info.steps.join('\n'),
    cues: info.cues.join('\n'),
    commonMistakes: info.mistakes.join('\n'),
  };
}
